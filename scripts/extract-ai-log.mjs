#!/usr/bin/env node
// Extracts an AI Audit log from Claude Code transcripts (~/.claude/projects/<slug>/*.jsonl).
//
// For every human prompt it records: AI tool + model, date/time (ISO), the
// prompt text, the AI's text answers and a compact list of the actions it
// took (files written/edited, commands run with their descriptions).
//
// Usage:
//   node scripts/extract-ai-log.mjs                       # auto-detect transcripts of this folder
//   node scripts/extract-ai-log.mjs --dir <transcripts dir> --out docs/AI_Log.md
//
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith('--') ? [...acc, [a.slice(2), all[i + 1]]] : acc), []),
);
const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const slug = repoRoot.replace(/[:\\/_.]/g, '-');
const dir = args.dir ?? path.join(os.homedir(), '.claude', 'projects', slug);
const out = args.out ?? path.join(repoRoot, 'docs', 'AI_Interaction_Log.md');
const MAX = Number(args.max ?? 1500); // max chars kept per AI answer

if (!fs.existsSync(dir)) {
  console.error(`Transcript folder not found: ${dir}\nPass --dir explicitly.`);
  process.exit(1);
}

// Privacy: never copy e-mail addresses or tokens into the report.
const redact = (s) =>
  s
    .replace(/[\w.+-]+@(?!eshop\.com|test\.local)[\w-]+\.[\w.]+/g, '<email>')
    .replace(/\b(gho|ghp|sk-ant)[-_A-Za-z0-9]{10,}/g, '<token>')
    .replace(/eyJ[\w-]{10,}\.[\w-]{10,}\.[\w-]{10,}/g, '<jwt>');

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.jsonl')).map((f) => path.join(dir, f));
const sessions = [];

for (const file of files) {
  const lines = fs.readFileSync(file, 'utf8').trim().split('\n').map((l) => {
    try { return JSON.parse(l); } catch { return null; }
  }).filter(Boolean);
  const interactions = [];
  let cur = null;
  let model = 'unknown';
  const start = (text, ts, kind) => {
    cur = { prompt: text, ts, kind, answers: [], actions: [] };
    interactions.push(cur);
  };
  for (const o of lines) {
    if (o.isSidechain) continue;
    if (o.type === 'user' && o.origin?.kind === 'human' && Array.isArray(o.message?.content)) {
      const text = o.message.content.filter((c) => c.type === 'text').map((c) => c.text).join('\n').trim();
      if (text) start(text, o.timestamp, 'prompt');
    } else if (o.type === 'attachment' && o.attachment?.type === 'queued_command' && o.attachment.humanTurn) {
      const text = (o.attachment.prompt ?? []).filter((c) => c.type === 'text').map((c) => c.text).join('\n');
      start(text, o.attachment.timestamp ?? o.timestamp, 'mid-turn message');
    } else if (o.type === 'assistant' && cur) {
      model = o.message?.model ?? model;
      for (const c of o.message?.content ?? []) {
        if (c.type === 'text' && c.text.trim()) cur.answers.push(c.text.trim());
        if (c.type === 'tool_use') {
          const i = c.input ?? {};
          const target = i.file_path ? path.relative(repoRoot, i.file_path) : i.description ?? i.pattern ?? i.skill ?? '';
          cur.actions.push(`${c.name}: ${String(target).replace(/\n/g, ' ').slice(0, 120)}`);
        }
      }
    }
  }
  if (interactions.length) sessions.push({ file: path.basename(file), model, interactions });
}

let md = '# AI Interaction Log (auto-extracted)\n\n';
md += `Generated by \`scripts/extract-ai-log.mjs\` on ${new Date().toISOString()} from Claude Code transcripts.\n\n`;
md += 'Each entry lists: AI tool, date/time (UTC, ISO 8601), the prompt, the AI output (text, truncated) and the actions the AI performed.\n\n';
let n = 0;
for (const s of sessions) {
  md += `## Session ${s.file.replace('.jsonl', '').slice(0, 8)} – Claude Code (model: ${s.model})\n\n`;
  for (const it of s.interactions) {
    n++;
    md += `### #${n} – ${it.ts} (${it.kind})\n\n`;
    md += `- **AI tool:** Claude Code (VS Code extension), model \`${s.model}\`\n`;
    md += `- **Prompt:**\n\n${redact(it.prompt).split('\n').map((l) => `  > ${l}`).join('\n')}\n\n`;
    const answer = redact(it.answers.join('\n\n'));
    md += `- **AI output (text, ${answer.length} chars${answer.length > MAX ? `, first ${MAX} shown` : ''}):**\n\n`;
    md += answer ? `${answer.slice(0, MAX).split('\n').map((l) => `  > ${l}`).join('\n')}\n\n` : '  > (no text output yet)\n\n';
    if (it.actions.length) {
      const counts = {};
      for (const a of it.actions) counts[a.split(':')[0]] = (counts[a.split(':')[0]] ?? 0) + 1;
      md += `- **Actions (${it.actions.length}):** ${Object.entries(counts).map(([k, v]) => `${k}×${v}`).join(', ')}\n\n`;
      md += '<details><summary>Action list</summary>\n\n';
      md += it.actions.map((a) => `- ${redact(a)}`).join('\n');
      md += '\n\n</details>\n\n';
    }
  }
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, md);
console.log(`Wrote ${n} interactions from ${sessions.length} session(s) to ${path.relative(process.cwd(), out)}`);
